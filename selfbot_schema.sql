-- Self-bot tables. Safe to re-run. Uses its own prefix so it can share a Supabase project with FitBot.
create table if not exists public.selfbot_jobs (
  id bigint generated by default as identity primary key,
  kind text not null default 'text',
  chat_ref text not null,
  interval_s integer not null,
  texts jsonb not null default '[]'::jsonb,
  name text default '',
  order_mode text not null default 'seq',
  jitter_pct integer not null default 0,
  end_at double precision,
  max_count integer,
  sent integer not null default 0,
  idx integer not null default 0,
  status text not null default 'active',
  next_run double precision not null default 0,
  last_error text default '',
  fails integer not null default 0,
  extra jsonb not null default '{}'::jsonb,
  created_by bigint default 0,
  created_at double precision default 0
);
create table if not exists public.selfbot_admins (
  user_id bigint primary key,
  name text default '',
  added_at timestamptz not null default now()
);
create table if not exists public.selfbot_triggers (
  id bigint generated by default as identity primary key,
  chat_ref text not null default '*',
  pattern text not null,
  response text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.selfbot_jobs enable row level security;
alter table public.selfbot_admins enable row level security;
alter table public.selfbot_triggers enable row level security;
